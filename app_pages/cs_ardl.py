import streamlit as st

from lib import style
from lib.content import MODELS

M = MODELS["CS-ARDL"]

st.title(f"{M['icon']} CS-ARDL — الإضافة المقطعية")
st.caption(f"{M['full']} · {M['authors']}")
style.stripe()

st.info(M["why"], icon=":material/lightbulb:")

# ------------------------------------------------------------------
st.header(":material/functions: الفكرة والمعادلة")

st.markdown(
    """
المشكلة التي يحلّها: عامل مشترك غير مرصود $f_t$ يؤثّر في المتغيّر التابع
والمفسّر معًا. حذفه من المعادلة يُنتج **تحيّز متغيّر محذوف**، فتصبح
PMG وMG غير متّسقتين.
"""
)

st.latex(r"y_{it} = \beta_i' x_{it} + \underbrace{\gamma_i' f_t}_{\text{غير مرصود}} + e_{it}")

st.markdown(
    """
والفكرة الجوهرية — **Common Correlated Effects** عند Pesaran (2006) —
أن المتوسّطات المقطعية للمتغيّرات المرصودة تحمل معلومة عن العوامل غير المرصودة،
فيمكن استعمالها وكيلًا عنها:
"""
)

st.latex(r"\bar{z}_t = (\bar{y}_t,\ \bar{x}_t')' \quad\longrightarrow\quad \text{وكيل عن } f_t")

st.markdown("ومع إضافة الديناميكا تُصبح المعادلة المُقدَّرة:")
st.latex(M["equation"])

c1, c2 = st.columns(2)
with c1:
    st.markdown("**المُعامل طويل الأجل (متوسّط مجموعة)**")
    st.latex(M["lr"])
with c2:
    st.markdown("**عدد إبطاءات المتوسّطات**")
    st.latex(M["ect"])

st.success(
    "قاعدة Chudik–Pesaran الإرشادية: عدد إبطاءات المتوسّطات المقطعية "
    "$p_T \\approx T^{1/3}$. فعند $T = 50$ تكون 3–4 إبطاءات، وعند $T = 100$ تكون 4–5.",
    icon=":material/rule:",
)

# ------------------------------------------------------------------
st.header(":material/checklist: الشروط والافتراضات")

t1, t2, t3 = st.tabs(["شروط البيانات", "الافتراضات النظرية", "CS-ARDL أم CS-DL؟"])

with t1:
    st.markdown(
        """
| الشرط | التفصيل |
|---|---|
| **N** | كبيرة ($\\ge 20$) — المتوسّطات المقطعية تحتاج وحدات كافية لتكون وكيلًا جيّدًا |
| **T** | كبيرة ($\\ge 50$ يفضّل) — تقدير منفصل لكل وحدة مع إبطاءات إضافية |
| رتب التكامل | I(0) و I(1) مسموح |
| اعتماد مقطعي | **موجود ومطلوب تبريره** باختبار CD |
| التوازن | يفضّل، والفجوات تُفسد المتوسّطات المقطعية |
"""
    )
    st.warning(
        "N الصغيرة تُفشل الفكرة من أساسها: متوسّط ثلاث أو أربع وحدات ليس وكيلًا "
        "موثوقًا عن عامل مشترك — بل هو ضجيج. هنا يصبح **SUR-ARDL** هو الخيار.",
        icon=":material/warning:",
    )

with t2:
    st.markdown(
        """
1. **عدد العوامل المشتركة محدود** وأقل من عدد المتغيّرات المرصودة + 1.
2. **تحميلات العوامل** $\\gamma_i$ عشوائية ومستقلّة عن الأخطاء.
3. **رتبة كافية (rank condition)** — مصفوفة متوسّطات التحميلات كاملة الرتبة،
   وهذا ما يجعل المتوسّطات المقطعية وكيلًا صالحًا.
4. **ميول غير متجانسة** مسموحة بل مفترضة — ولذا يُؤخذ المتوسّط.
5. **الأخطاء المتبقّية** مستقلّة مقطعيًا **بعد** الإضافة — وهذا يُختبر.
"""
    )
    st.info(
        "الفحص الختامي الحاسم: أعد اختبار **CD على بواقي CS-ARDL**. "
        "إن بقي الاعتماد معنويًا فالعوامل لم تُلتقط، والنموذج لم يُصلح المشكلة.",
        icon=":material/fact_check:",
    )

with t3:
    st.markdown(
        """
**CS-DL** (Cross-Sectionally augmented Distributed Lag) نسخة بلا متغيّر تابع مُبطّأ.

| | CS-ARDL | CS-DL |
|---|---|---|
| متغيّر تابع مُبطّأ | نعم | لا |
| الديناميكا قصيرة الأجل | متاحة | غير متاحة |
| الأداء عند T < 50 | أضعف | **أفضل** |
| الأداء عند T كبيرة | جيّد | جيّد |
| تحيّز العيّنة الصغيرة | أعلى | أقل |

**القاعدة:** إن كانت $T < 50$ فجرّب CS-DL وقارن. وإن كنت تحتاج الديناميكا
قصيرة الأجل فلا بديل عن CS-ARDL.
"""
    )

