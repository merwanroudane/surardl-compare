import streamlit as st

from lib import style

st.title(":material/school: المفاهيم الأساسية")
st.caption("ما يجب أن يكون واضحًا قبل اختيار أي من النماذج الأربعة")
style.stripe()

t1, t2, t3, t4, t5 = st.tabs(
    ["رتبة التكامل", "التكامل المشترك", "تصحيح الخطأ", "الاعتماد المقطعي", "التجانس"]
)

# ----------------------------------------------------------------- 1
with t1:
    st.header("رتبة التكامل — Order of integration")

    st.markdown(
        """
السلسلة **I(0)** ساكنة: متوسطها وتباينها ثابتان، والصدمة تتلاشى.
السلسلة **I(1)** تحتاج فرقًا واحدًا لتصبح ساكنة، والصدمة فيها **دائمة**.

لماذا يهمّ هذا؟ لأن انحدار سلسلتين I(1) غير مرتبطتين يُعطي $R^2$ مرتفعًا
و$t$ معنويًا **بلا أي علاقة حقيقية** — وهو ما يسمّى الانحدار الزائف
(spurious regression).
"""
    )

    st.latex(r"y_t = \rho\, y_{t-1} + \varepsilon_t")

    c1, c2 = st.columns(2)
    with c1:
        st.success(
            "**ρ < 1 ⟹ I(0)**  \n"
            "الصدمة تتلاشى أُسّيًا. المتوسط يعود إلى قيمته.",
            icon=":material/trending_down:",
        )
    with c2:
        st.warning(
            "**ρ = 1 ⟹ I(1)**  \n"
            "الصدمة تبقى إلى الأبد. لا متوسط يُعاد إليه.",
            icon=":material/trending_flat:",
        )

    st.subheader("لماذا يتميّز ARDL هنا")

    st.markdown(
        """
منهجيات Engle–Granger و Johansen تشترط أن تكون **كل** المتغيّرات من نفس الرتبة،
عادةً I(1). وهذا يُحمّل النتيجة كاملةً على اختبارات جذر الوحدة — وهي اختبارات
ضعيفة القوة في العيّنات الصغيرة.

منهجية الحدود في ARDL **تقبل خليطًا** من I(0) و I(1). وهذه هي ميزتها العملية
الأولى: تتجنّب الاعتماد على تصنيف قد يكون خاطئًا.
"""
    )

    st.error(
        "**لكن I(2) ممنوعة في النماذج الأربعة جميعًا.** وجود متغيّر I(2) يُبطل "
        "نظرية اختبار الحدود: إحصاءة F لا تعود محصورة بين الحدّين المجدولين. "
        "لذلك يبقى اختبار جذر الوحدة ضروريًا — لا للتصنيف، بل **لاستبعاد I(2)**.",
        icon=":material/block:",
    )

# ----------------------------------------------------------------- 2
with t2:
    st.header("التكامل المشترك — Cointegration")

    st.markdown(
        """
سلسلتان I(1) تتحرّكان معًا على المدى الطويل إن وُجدت تركيبة خطّية بينهما ساكنة:
"""
    )
    st.latex(r"y_t - \beta x_t = u_t \sim I(0)")

    st.markdown(
        """
هذا يعني أن انحرافهما عن بعضهما **مؤقّت**، وإن ابتعدتا فثمّة قوّة تُعيدهما.
المتّجه $(1, -\\beta)$ هو **متّجه التكامل المشترك**، و$\\beta$ هو المُعامل
طويل الأجل الذي نريد تقديره.

### اختبار الحدود: لماذا حدّان لا حدّ واحد؟

لأن التوزيع الحدّي لإحصاءة F يعتمد على رتب تكامل المتغيّرات المفسّرة،
وهي غير معلومة يقينًا. فبدل قيمة حرجة واحدة، يُقدّم Pesaran وآخرون طرفين:
"""
    )

    st.markdown(
        """
| الحالة | التفسير |
|---|---|
| F فوق الحدّ الأعلى I(1) | **يوجد** تكامل مشترك — مهما كانت رتب التكامل |
| F تحت الحدّ الأدنى I(0) | **لا يوجد** تكامل مشترك — مهما كانت الرتب |
| F بين الحدّين | **غير حاسم** — تحتاج معرفة الرتب فعلًا |
"""
    )

    st.info(
        "المنطقة الوسطى ليست فشلًا بل **إفصاحًا أمينًا**: الاختبار يقول إن البيانات "
        "لا تكفي للحسم دون معرفة إضافية. عندها ارجع إلى اختبارات جذر الوحدة، "
        "أو استعمل قيمًا حرجة أدقّ للعيّنات الصغيرة.",
        icon=":material/help:",
    )

    st.markdown(
        """
### أي قيم حرجة تستعمل؟

| المصدر | متى |
|---|---|
| Pesaran وآخرون (2001) | T كبيرة (≥ 500) — القيم مقاربية |
| Narayan (2005) | **T صغيرة (30–80)** — وهي حالة معظم التطبيقات |
| Kripfganz & Schneider (2020) | أي T و k — سطوح استجابة وقيم احتمالية تقريبية |

استعمال قيم 2001 المقاربية على عيّنة من 35 مشاهدة **يُفرط في الرفض**.
هذا خطأ شائع جدًا في الأدبيات التطبيقية.
"""
    )

# ----------------------------------------------------------------- 3
with t3:
    st.header("نموذج تصحيح الخطأ — Error Correction Model")

    st.markdown("إعادة كتابة ARDL في صورة ECM هي حجر الأساس في النماذج الأربعة:")

    st.latex(
        r"\Delta y_t = c + \underbrace{\lambda}_{\text{سرعة التعديل}}"
        r"\Big(y_{t-1} - \underbrace{\beta' x_{t-1}}_{\text{التوازن طويل الأجل}}\Big)"
        r" + \underbrace{\sum \psi_i \Delta y_{t-i} + \sum \phi_j \Delta x_{t-j}}"
        r"_{\text{الديناميكا قصيرة الأجل}} + \varepsilon_t"
    )

    st.markdown(
        """
المعادلة تفصل بوضوح بين ثلاث طبقات:

- **التوازن طويل الأجل** $\\beta$ — العلاقة التي تعود إليها المتغيّرات.
- **سرعة التعديل** $\\lambda$ — ما نسبة الانحراف التي تُصحَّح كل فترة.
- **الديناميكا قصيرة الأجل** — السلوك العابر خلال التعديل.
"""
    )

    st.subheader("قراءة سرعة التعديل λ")

    st.markdown(
        """
| قيمة λ | المعنى | الحكم |
|---|---|---|
| $\\lambda \\ge 0$ | لا تصحيح — النظام يتباعد | **لا تكامل مشترك** |
| $-1 < \\lambda < 0$ | تصحيح أُسّي سلس | الحالة السليمة |
| $\\lambda = -1$ | تصحيح كامل في فترة واحدة | سريع جدًا |
| $\\lambda < -1$ | تصحيح مفرط متذبذب | يبقى مستقرًا حتى $-2$، لكن راجع النموذج |
| $\\lambda < -2$ | تباعد متفجّر | **خطأ في التوصيف** |

نصف العمر: $\\;t_{1/2} = \\ln(0.5)/\\ln(1+\\lambda)$.
فعند $\\lambda = -0.25$ يُصحَّح نصف الانحراف خلال نحو **2.4 فترة**.
"""
    )

    st.warning(
        "شرط ضروري لا يُتهاون فيه: **λ سالب ومعنوي**. "
        "إن كان λ غير معنوي فلا معنى لتفسير المعاملات طويلة الأجل — "
        "لأنها نسبة مقامها صفر إحصائيًا: $\\beta = -\\pi/\\lambda$.",
        icon=":material/priority_high:",
    )

# ----------------------------------------------------------------- 4
with t4:
    st.header("الاعتماد المقطعي — Cross-sectional dependence")

    st.markdown(
        """
وحدات اللوحة (دول، شركات، أقاليم) نادرًا ما تكون مستقلّة. صدمة النفط تضرب
الجميع، والأزمة المالية تنتقل، والجيرة الجغرافية تنقل الأثر.

رياضيًا: $\\;\\mathrm{Cov}(\\varepsilon_{it}, \\varepsilon_{jt}) = \\sigma_{ij} \\neq 0$.

**والنقطة الحاسمة أن هناك نوعين مختلفين تمامًا من هذا الاعتماد**، ولكلٍّ علاجه:
"""
    )

    c1, c2 = st.columns(2, gap="large")

    with c1:
        with st.container(border=True):
            st.markdown("### :material/share: اعتماد **ضعيف**")
            st.markdown(
                """
ارتباط معاصر بين الأخطاء فقط، بلا عامل مشترك يدخل في المتغيّرات المفسّرة.

- المقدّرات تبقى **متّسقة**
- لكنها **غير كفؤة**
- الحلّ: استثمر الارتباط في مصفوفة $\\Sigma$

:violet-badge[⟵ هذا مجال **SUR-ARDL**]

اختباره: **Breusch–Pagan LM**
"""
            )

    with c2:
        with st.container(border=True):
            st.markdown("### :material/hub: اعتماد **قوي**")
            st.markdown(
                """
عامل مشترك غير مرصود $f_t$ يؤثّر في $y$ و$x$ معًا.

- المقدّرات تصبح **غير متّسقة**
- المشكلة متغيّر محذوف لا كفاءة
- الحلّ: أضف وكلاء للعامل

:orange-badge[⟵ هذا مجال **CS-ARDL**]

اختباره: **Pesaran CD**
"""
            )

    st.markdown(
        """
```mermaid
flowchart TD
    A["اعتماد مقطعي مرصود"] --> B{"هل العامل المشترك<br/>يدخل المتغيّرات المفسّرة؟"}
    B -->|"نعم — اعتماد قوي"| C["تحيّز متغيّر محذوف<br/>عدم اتّساق"]
    B -->|"لا — ارتباط أخطاء فقط"| D["اتّساق محفوظ<br/>لكن كفاءة مفقودة"]
    C --> E["CS-ARDL<br/>متوسّطات مقطعية"]
    D --> F["SUR-ARDL<br/>وزن بـ Σ"]
    style E fill:#FFF3E0,stroke:#EF6C00,stroke-width:2px,color:#E65100
    style F fill:#F3E5F5,stroke:#6A1B9A,stroke-width:2px,color:#4A148C
```
"""
    )

    st.error(
        "**الخطأ الأكثر شيوعًا في هذا الباب**: استعمال اختبار CD لتبرير SUR، "
        "أو BP لتبرير CS-ARDL. الاختباران يقيسان الظاهرة نفسها لكن القرار "
        "المبني عليهما مختلف تمامًا، ويتوقّف على **مصدر** الاعتماد لا على وجوده.",
        icon=":material/dangerous:",
    )

# ----------------------------------------------------------------- 5
with t5:
    st.header("التجانس — Homogeneity")

    st.markdown(
        """
السؤال: هل المعامل طويل الأجل نفسه في كل الوحدات، أم لكل وحدة معاملها؟

هذه مفاضلة كلاسيكية بين **التحيّز** و**التباين**:
"""
    )

    st.markdown(
        """
| الموقف | المقدّر | إن صحّ القيد | إن بطل القيد |
|---|---|---|---|
| كل شيء مجمّع | **DFE** | أكفأ | متحيّز بشدّة |
| الأجل الطويل مقيّد فقط | **PMG** | كفء ومتّسق | **غير متّسق** |
| كل شيء حر ثم متوسّط | **MG** | أقل كفاءة | متّسق |
| كل شيء حر بلا متوسّط | **SUR-ARDL** | — | متّسق دائمًا |
"""
    )

    st.info(
        "لاحظ الفرق البنيوي: PMG وMG وDFE تُنتج **رقمًا واحدًا** يلخّص اللوحة. "
        "أمّا SUR-ARDL فيُنتج **N معاملًا** — ويُقدّم اختبارًا رسميًا لتساويها. "
        "هو لا يفترض التجانس ولا ينفيه، بل **يختبره**.",
        icon=":material/balance:",
    )

    st.subheader("كيف يُحسم القيد عمليًا")

    st.markdown(
        """
1. قدّر **MG** (متّسق دائمًا تحت عدم التجانس) و**PMG** (كفء تحت التجانس).
2. طبّق **Hausman**: فرضية العدم أن الفرق بين المقدّرين منهجي معدوم.
3. **لم تُرفض** ⟹ القيد صحيح ⟹ استعمل PMG (الأكفأ).
4. **رُفضت** ⟹ PMG غير متّسق ⟹ استعمل MG.
5. كرّر المقارنة مع DFE بالمنطق نفسه.

ويدعم ذلك اختبار **Pesaran–Yamagata** لتجانس الميول مباشرةً.
"""
    )
